// "Ebb (low energy, unpleasant)".
export function quadrantLabel(q: Quadrant, mode: CommunicationMode): string {
  const { name, subtitle } = copy.quadrants[q];
  return mode === 'literal' ? `${name} (${subtitle.toLowerCase()})` : name;
}
