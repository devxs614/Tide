export interface ModeText {
  gentle: string;
  direct: string;
  literal: string;
}

export function byMode(text: ModeText, mode: CommunicationMode): string {
  return text[mode];
}

// Replaces {name} placeholders. Missing values are left visible on purpose so
// a broken template is easy to spot in review instead of silently blank.
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}

